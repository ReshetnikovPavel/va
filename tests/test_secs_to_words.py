import pytest

from va import nlp


@pytest.mark.parametrize(
    ("secs", "expected"),
    [
        # секунды: согласование 1 / 2-4 / 5-20
        (0, "ноль секунд"),
        (1, "одна секунда"),
        (2, "две секунды"),
        (3, "три секунды"),
        (4, "четыре секунды"),
        (5, "пять секунд"),
        (11, "одиннадцать секунд"),
        (21, "двадцать одна секунда"),
        (22, "двадцать две секунды"),
        (25, "двадцать пять секунд"),
        (30, "тридцать секунд"),
        (59, "пятьдесят девять секунд"),
        # минуты
        (60, "одна минута"),
        (61, "одна минута одна секунда"),
        (65, "одна минута пять секунд"),
        (90, "одна минута тридцать секунд"),
        (120, "две минуты"),
        (125, "две минуты пять секунд"),
        (121, "две минуты одна секунда"),
        # часы: час мужского рода
        (3600, "один час"),
        (3601, "один час одна секунда"),
        (3661, "один час одна минута одна секунда"),
        (7200, "два часа"),
        (7500, "два часа пять минут"),
        (75600, "двадцать один час"),
        (79200, "двадцать два часа"),
        (86399, "двадцать три часа пятьдесят девять минут пятьдесят девять секунд"),
    ],
)
def test_secs_to_words_nominative(secs, expected):
    assert nlp.secs_to_words(secs, "nomn") == expected


